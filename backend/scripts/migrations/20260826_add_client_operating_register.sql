  UNIQUE KEY `uk_client_operating_register_match` (`clinic_id`, `canonical_match_key`),
  KEY `idx_client_operating_register_profile` (`client_account_profile_id`),
  KEY `idx_client_operating_register_kind` (`clinic_id`, `record_kind`, `freshness_status`),
  KEY `idx_client_operating_register_source_list` (`clinic_id`, `source_system`, `source_list_id`, `last_seen_at`),
